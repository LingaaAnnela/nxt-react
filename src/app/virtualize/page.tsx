// Client Component: the demo needs scroll events, tab state, and live DOM
// counting — all of which require a running browser environment.
'use client';

import { useState, useMemo, useEffect } from 'react';
import { useGetProductsQuery } from '@/lib/redux/api';
import { formatPrice } from '@/lib/shop/format';
import styles from './page.module.css';

const CONTAINER_H = 480; // px — visible scroll area
const ITEM_H = 80;       // px — every row is exactly this tall (fixed-size constraint)

// ─── core virtualisation hook ──────────────────────────────────────────────
// Translates scrollTop into the slice of items that need to be in the DOM.
// Production libraries (react-window, @tanstack/react-virtual) apply the
// same math with extra handling for variable heights, scroll correction,
// and ResizeObserver. The idea here is that all of it fits in ~15 lines.
function useVirtual(count: number) {
  const [scrollTop, setScrollTop] = useState(0);

  const overscan = 2; // render 2 extra rows above and below the viewport
  const start = Math.max(0, Math.floor(scrollTop / ITEM_H) - overscan);
  const visible = Math.ceil(CONTAINER_H / ITEM_H);
  const end = Math.min(count - 1, start + visible + overscan * 2);

  return {
    virtualItems: Array.from({ length: end - start + 1 }, (_, i) => ({
      index: start + i,
      top: (start + i) * ITEM_H, // absolute offset within the container
    })),
    totalHeight: count * ITEM_H, // spacer height so the scrollbar is correct
    onScroll: (e: React.UIEvent<HTMLDivElement>) =>
      setScrollTop(e.currentTarget.scrollTop),
  };
}

// ─── row component ─────────────────────────────────────────────────────────
// useEffect fires on mount (→ vrow:mount) and cleans up on unmount
// (→ vrow:unmount). The page listens for these events to maintain a live
// count of how many row nodes currently exist in the DOM.
// style is undefined in "all" mode; absolute-position object in virtual mode.
function VirtualRow({
  name,
  category,
  priceCents,
  style,
}: {
  name: string;
  category: string;
  priceCents: number;
  style?: React.CSSProperties;
}) {
  useEffect(() => {
    window.dispatchEvent(new CustomEvent('vrow:mount'));
    return () => void window.dispatchEvent(new CustomEvent('vrow:unmount'));
  }, []); // empty deps: fire once on mount, clean up on unmount

  return (
    <div className={styles.row} style={style}>
      <div className={styles.rowName}>{name}</div>
      <div className={styles.rowMeta}>
        <span className={styles.rowCategory}>{category}</span>
        <span className={styles.rowPrice}>{formatPrice(priceCents)}</span>
      </div>
    </div>
  );
}

// ─── page ──────────────────────────────────────────────────────────────────
export default function VirtualizePage() {
  const { data: products = [], isLoading } = useGetProductsQuery();
  const [mode, setMode] = useState<'all' | 'virtual'>('all');
  const [mountedCount, setMountedCount] = useState(0);

  // 500 items generated by repeating the real product catalogue.
  // useMemo: stable reference so the list doesn't regenerate on re-renders.
  const items = useMemo(
    () =>
      products.length === 0
        ? []
        : Array.from({ length: 500 }, (_, i) => ({
            id: `vi-${i}`,
            name: `${products[i % products.length].name} #${i + 1}`,
            category: products[i % products.length].category,
            priceCents: products[i % products.length].priceCents,
          })),
    [products],
  );

  // Aggregate mount/unmount events from all VirtualRow instances.
  // This is the live DOM count — not a React state estimate.
  useEffect(() => {
    const up = () => setMountedCount((c) => c + 1);
    const dn = () => setMountedCount((c) => c - 1);
    window.addEventListener('vrow:mount', up);
    window.addEventListener('vrow:unmount', dn);
    return () => {
      window.removeEventListener('vrow:mount', up);
      window.removeEventListener('vrow:unmount', dn);
    };
  }, []);

  const { virtualItems, totalHeight, onScroll } = useVirtual(items.length);

  if (isLoading) return <p className={styles.loading}>Loading…</p>;

  return (
    <main className={styles.page}>
      <h1 className={styles.heading}>List Virtualisation</h1>
      <p className={styles.subtitle}>
        {items.length} items — watch the &ldquo;Rows in DOM&rdquo; counter as you scroll
      </p>

      <div className={styles.callout}>
        <p>
          Rendering 500 items naively creates 500 DOM nodes — layout, style,
          paint, and memory costs for everything, visible or not. Virtualisation
          renders only the rows that fit in the viewport (plus a small overscan
          buffer). DOM node count stays constant at ~{Math.ceil(CONTAINER_H / ITEM_H) + 4} regardless of
          list length.
        </p>
        <p>
          The <strong>Rows in DOM</strong> counter updates live via{' '}
          <code>useEffect</code> mount/unmount events in each row. Switch tabs
          and watch it jump from 500 to ~{Math.ceil(CONTAINER_H / ITEM_H) + 4}. Then scroll in
          virtualised mode — the count holds steady while content streams past.
        </p>
        <p className={styles.calloutNote}>
          The <code>useVirtual</code> hook in this file implements the scroll-position
          math manually (~15 lines). In production, use{' '}
          <code>react-window</code> (FixedSizeList / FixedSizeGrid) or{' '}
          <code>@tanstack/react-virtual</code> (no wrapper element, variable
          heights). They solve edge cases this demo skips: keyboard focus
          management, scrollTo(), and ResizeObserver for dynamic container sizes.
        </p>
      </div>

      <div className={styles.toolbar}>
        <div className={styles.tabs} role="tablist">
          <button
            type="button"
            role="tab"
            aria-selected={mode === 'all'}
            className={mode === 'all' ? styles.tabActive : styles.tab}
            onClick={() => setMode('all')}
          >
            All 500 rendered
          </button>
          <button
            type="button"
            role="tab"
            aria-selected={mode === 'virtual'}
            className={mode === 'virtual' ? styles.tabActive : styles.tab}
            onClick={() => setMode('virtual')}
          >
            Virtualised
          </button>
        </div>

        <div className={styles.counter}>
          <span className={styles.counterLabel}>Rows in DOM</span>
          <span className={styles.counterValue}>{mountedCount}</span>
        </div>
      </div>

      {mode === 'all' ? (
        // Naive mode: all 500 nodes in the DOM at once.
        <div className={styles.scroll}>
          {items.map((item) => (
            <VirtualRow
              key={item.id}
              name={item.name}
              category={item.category}
              priceCents={item.priceCents}
            />
          ))}
        </div>
      ) : (
        // Virtual mode: one tall spacer div sets the scrollbar height.
        // Each row is absolutely positioned at its computed top offset.
        // Only the rows inside the viewport window are rendered.
        <div className={styles.scroll} onScroll={onScroll}>
          <div style={{ height: totalHeight, position: 'relative' }}>
            {virtualItems.map(({ index, top }) => (
              <VirtualRow
                key={items[index].id}
                name={items[index].name}
                category={items[index].category}
                priceCents={items[index].priceCents}
                style={{ position: 'absolute', top, left: 0, right: 0 }}
              />
            ))}
          </div>
        </div>
      )}
    </main>
  );
}
